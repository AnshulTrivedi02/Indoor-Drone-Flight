#!/usr/bin/env python3
"""Generate docs/thesis/ekf3_heading_replay/numbers_ekf3_heading.md from
eval/results/ekf3_heading_replay/scored.json and gates.json. Every number is rd() of
eval/figs_thesis.py's own rounding function, loaded through the AST (function only, not the
whole module -- the same pattern eval/cl_heading_perflight.py uses).

--check is a REAL cross-check against the result JSONs, POSITIONAL, not a substring search: it
rebuilds every data-table row FRESH from a fresh read of scored.json/gates.json/clamped_share.json
/iyaw_diag.json (recomputed with rd(), independently of whatever is on disk), and asserts that
EXACT, WHOLE LINE (bag name + every column value, in order) is present verbatim as one of the
lines in the markdown file already on disk. A whole-line check cannot be defeated by a short,
common value like "0" or "n/a" appearing elsewhere in the file (the earlier substring-search draft
could be) -- a wrong single cell changes the whole row's text, so the row fails to match anything
on disk.

Usage:
  eval/ekf3_heading_numbers_gen.py            # write the file
  eval/ekf3_heading_numbers_gen.py --check    # positionally cross-check the file already on disk
"""
import ast, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "docs", "thesis", "ekf3_heading_replay", "numbers_ekf3_heading.md")
RESULTS = os.path.join(HERE, "results", "ekf3_heading_replay")


def _load_rd():
    tree = ast.parse(open(os.path.join(HERE, "figs_thesis.py")).read())
    keep = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "rd"]
    ns = {}
    exec(compile(ast.Module(body=keep, type_ignores=[]), "eval/figs_thesis.py", "exec"), ns)
    return ns["rd"]


rd = _load_rd()

BAGS = [f"{p}_{w}_r{r}" for p in ("fwdc", "fwdplainc") for w in ("tex", "trans", "blank") for r in (1, 2, 3)]
FLOOR = ("the EKF3 5 deg `angErr` floor (`AP_NavEKF3_Measurements.cpp:1118`) applies "
         "unconditionally to every EKF3+heading number on this page")

ARM_KEY = {"EKF3 (i)": "EKF3_baseline_arm_i", "EKF3 (ii)": "EKF3_heading_arm_ii",
           "UKF (iii)": "UKF_heading5_arm_iii", "FGO (iv)": "FGO_heading5_arm_iv"}


def num(raw_value, digits, nan_text="undefined (Umeyama degenerate)"):
    if raw_value is None or (isinstance(raw_value, float) and raw_value != raw_value):
        return nan_text
    return rd(raw_value, digits)


def build(scored, gates, clamped=None, iyaw=None):
    """Returns (markdown_lines, row_ledger). row_ledger: the exact text of every DATA-table row
    this function emits (header/separator rows excluded) -- see module docstring for why
    --check matches whole lines, not substrings."""
    lines, row_ledger = [], []

    def emit(s, is_row=False):
        lines.append(s)
        if is_row:
            row_ledger.append(s)

    lines.append("# EKF3 heading Replay -- thesis-facing numbers")
    lines.append("")
    lines.append("Generated by `eval/ekf3_heading_numbers_gen.py` from "
                 "`eval/results/ekf3_heading_replay/scored.json` and `gates.json`. "
                 "Every value is `rd()` of `eval/figs_thesis.py` (loaded via the AST), "
                 "applied once to the full-precision stored value.")
    lines.append("")
    lines.append(f"**Standing caveat: {FLOOR}.**")
    lines.append("")
    lines.append("**The 0.148 deg (`fwdc`) / 0.126 deg (`fwdplainc`) UKF/FGO heading arms quoted elsewhere "
                 "(numbers.md section 6.6) are the STORED Phase 4 references -- they are NOT re-run here. "
                 "Arms (iii)/(iv) on this page are a SEPARATE run at a shared 5 deg sigma, so EKF3's forced "
                 "5 deg floor is compared against the UKF/FGO under the SAME sigma.**")
    lines.append("")
    lines.append("## Gates")
    lines.append("")
    lines.append(f"- Round-trip check: **{gates['round_trip_check']['verdict']}**")
    lines.append(f"- Arm (i) reproduction (18/18 bags): **{gates['arm_i_reproduction']['verdict']}**")
    lines.append(f"- Sign check (node convention): **{gates['sign_check']['verdict']}**")
    lines.append(f"- Sigma-option byte-identity proof: **{gates['sigma_option_byte_identity_proof']['overall_verdict']}**")
    lines.append("")

    lines.append("## Per-bag table: evo -a (cruise), m")
    lines.append("")
    lines.append("| bag | EKF3 (i) no heading | EKF3 (ii) +heading (5 deg floor) | UKF (iii) +heading 5 deg | FGO (iv) +heading 5 deg |")
    lines.append("|---|---|---|---|---|")
    for bag in BAGS:
        r = scored[bag]
        c = [num(r[ARM_KEY[k]]["evo_a_cruise"], 3) for k in ("EKF3 (i)", "EKF3 (ii)", "UKF (iii)", "FGO (iv)")]
        emit(f"| {bag} | {c[0]} | {c[1]} | {c[2]} | {c[3]} |", is_row=True)
    lines.append("")

    lines.append("## Per-bag table: yaw error end-of-cruise / drift, deg / deg-per-min")
    lines.append("")
    lines.append("| bag | EKF3 (i) end/drift | EKF3 (ii) end/drift | UKF (iii) end/drift | FGO (iv) end/drift |")
    lines.append("|---|---|---|---|---|")
    for bag in BAGS:
        r = scored[bag]
        parts = []
        for k in ("EKF3 (i)", "EKF3 (ii)", "UKF (iii)", "FGO (iv)"):
            d = r[ARM_KEY[k]]
            parts.append(f"{num(d['yaw_err_end_deg'], 2)} / {num(d['yaw_err_drift_dpm'], 3)}")
        emit(f"| {bag} | {parts[0]} | {parts[1]} | {parts[2]} | {parts[3]} |", is_row=True)
    lines.append("")

    lines.append("## Per-bag table: failure metrics (disp_ratio / onset GT distance, m)")
    lines.append("")
    lines.append("| bag | EKF3 (i) | EKF3 (ii) | UKF (iii) | FGO (iv) |")
    lines.append("|---|---|---|---|---|")
    for bag in BAGS:
        r = scored[bag]
        parts = []
        for k in ("EKF3 (i)", "EKF3 (ii)", "UKF (iii)", "FGO (iv)"):
            f = r[ARM_KEY[k]]["failure"]
            onset = "n/a" if f["onset_gt_dist"] is None else num(f["onset_gt_dist"], 1)
            parts.append(f"{num(f['disp_ratio'], 3)} / {onset}")
        emit(f"| {bag} | {parts[0]} | {parts[1]} | {parts[2]} | {parts[3]} |", is_row=True)
    lines.append("")

    lines.append("## max |delta yaw| between arm (ii) and arm (i), transition/blank bags "
                 "(evo cannot separate the two there -- position is frozen)")
    lines.append("")
    lines.append("| bag | arm(ii) end yaw err deg | arm(i) end yaw err deg | |delta| deg |")
    lines.append("|---|---|---|---|")
    for bag in BAGS:
        if "_trans_" not in bag and "_blank_" not in bag:
            continue
        r = scored[bag]
        a2 = r["EKF3_heading_arm_ii"]["yaw_err_end_deg"]
        a1 = r["EKF3_baseline_arm_i"]["yaw_err_end_deg"]
        emit(f"| {bag} | {num(a2, 2)} | {num(a1, 2)} | {num(abs(a2 - a1), 2)} |", is_row=True)
    lines.append("")

    lines.append("## Heading NIS, arms (iii)/(iv) at 5 deg sigma (median / % over gate)")
    lines.append("")
    lines.append("| bag | UKF (iii) | FGO (iv) |")
    lines.append("|---|---|---|")
    for bag in BAGS:
        r = scored[bag]
        u, f = r["UKF_heading5_arm_iii"]["nis_psi"], r["FGO_heading5_arm_iv"]["nis_psi"]
        emit(f"| {bag} | {num(u['median'], 4)} / {num(u['pct_over_gate'], 2)}% | "
             f"{num(f['median'], 4)} / {num(f['pct_over_gate'], 2)}% |", is_row=True)
    lines.append("")

    if clamped is not None:
        lines.append("## Clamped-share diagnostic, arm (ii) (DERIVED, not instrumented -- "
                     "preregistration section 0 item 1; see eval/ekf3_heading_clamped_share.py's "
                     "docstring for the full derivation)")
        lines.append("")
        lines.append("| bag | n injected | n clamped | clamped share % | n timeStamp_ms gaps < 20 ms |")
        lines.append("|---|---|---|---|---|")
        for bag in BAGS:
            c = clamped["per_bag"][bag]
            emit(f"| {bag} | {num(c['n_records'], 0)} | {num(c['n_clamped'], 0)} | "
                 f"{num(100 * c['clamped_share'], 2)} | {num(c['n_short_gap_lt_20ms'], 0)} |", is_row=True)
        lines.append("")

    if iyaw is not None:
        lines.append("## EKF3-side yaw innovation (IYAW), arm (ii), after the first injected record "
                     "(DIAGNOSTIC -- log-cadence snapshot, NOT a per-fusion or fused/rejected count; "
                     "fused angErr before EKF3's own floor is 5 deg -- see "
                     "eval/ekf3_heading_iyaw_diag.py's docstring)")
        lines.append("")
        lines.append("| bag | n XKF3 rows (== n XKF1 rows) | IYAW mean deg | IYAW median deg | IYAW p95 abs deg | IYAW max abs deg |")
        lines.append("|---|---|---|---|---|---|")
        for bag in BAGS:
            d = iyaw[bag]
            s = d["iyaw_deg_after_first_injection"]
            same = "yes" if d["n_xkf1_core100"] == d["n_xkf3_core100"] else "no"
            emit(f"| {bag} | {num(d['n_xkf3_core100'], 0)} ({same}) | {num(s['mean'], 4)} | "
                 f"{num(s['median'], 4)} | {num(s['p95_abs'], 4)} | {num(s['max_abs'], 4)} |", is_row=True)
        lines.append("")

    lines.append("## Dataset-level caveats carried from numbers.md section 6.6 (unchanged by this stage)")
    lines.append("")
    lines.append("- **`fwdplainc_tex` (checkerboard floor, plain walls): no heading benefit is claimed.** "
                 "The heading measurement FAILED Phase 3 validation on this floor/wall combination "
                 "(0/3; numbers.md section 6.6/8). Arm (ii)'s numbers on `fwdplainc_tex_r1-r3` are "
                 "reported as computed, not as a validated improvement.")
    lines.append("- **`fwdplainc_blank` (blank floor): yaw benefit only; position is NOT bounded** "
                 "(no flow signal on this floor; numbers.md section 6.6). Arm (ii)'s evo -a (cruise) is "
                 "undefined there (the replayed EKF3 position estimate is exactly stationary over the "
                 "pinned cruise window); see the failure-metrics table above instead.")
    lines.append("")

    lines.append("## Stored UKF/FGO heading arm references (NOT re-run; 0.148/0.126 deg sigma; "
                 "numbers.md section 6.6)")
    lines.append("")
    lines.append("- `fwdc` UKF/FGO +heading: 0.148 deg sigma (stored)")
    lines.append("- `fwdplainc` UKF/FGO +heading: 0.126 deg sigma (stored)")
    lines.append("")
    return lines, row_ledger


def main():
    check = "--check" in sys.argv
    scored = json.load(open(os.path.join(RESULTS, "scored.json")))
    gates = json.load(open(os.path.join(RESULTS, "gates.json")))
    clamped_path = os.path.join(RESULTS, "clamped_share.json")
    iyaw_path = os.path.join(RESULTS, "iyaw_diag.json")
    clamped = json.load(open(clamped_path)) if os.path.exists(clamped_path) else None
    iyaw = json.load(open(iyaw_path)) if os.path.exists(iyaw_path) else None
    lines, row_ledger = build(scored, gates, clamped, iyaw)
    text = "\n".join(lines) + "\n"

    if check:
        if not os.path.exists(OUT):
            print(f"CHECK: FAIL (file does not exist: {OUT})")
            sys.exit(1)
        on_disk_lines = set(open(OUT).read().splitlines())
        missing = [row for row in row_ledger if row not in on_disk_lines]
        if missing:
            print(f"CHECK: FAIL -- {len(missing)}/{len(row_ledger)} freshly-computed data rows not "
                  f"found as a WHOLE LINE in the on-disk file (file is stale or a cell is wrong). "
                  f"First few:")
            for m in missing[:10]:
                print(f"  {m!r}")
            sys.exit(1)
        print(f"CHECK: PASS -- all {len(row_ledger)} freshly-computed data rows (independently "
              f"recomputed from scored.json/gates.json/clamped_share.json/iyaw_diag.json) found "
              f"as exact whole lines in the on-disk file")
        sys.exit(0)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"[out] {OUT} ({len(row_ledger)} ledgered rows)")


if __name__ == "__main__":
    main()
