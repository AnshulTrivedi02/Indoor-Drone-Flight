#!/usr/bin/env python3
"""Generate Gazebo models for AprilTag tag36h11 IDs (experiments T and L). Source images: AprilRobotics/apriltag-imgs
(tag36h11, 10x10 px including the 1-px white border), upscaled x40 with NEAREST so the rendered edges stay sharp.
Each model: model://apriltag36h11_<id>, a visual-only thin box (no collision: the world keeps exactly one ground
collision plane, Known Issue #11) of overall side SIDE_M; the black square (the edge pupil_apriltags' pose estimate
uses as tag_size) is 8/10 of it. Pose in the world: the tag's centre; +x of the image = model +x, image up = model +y.
Usage: python3 sim/tools/make_apriltag_models.py [--ids 0-19] [--side 0.5]"""
import argparse, os, urllib.request
import numpy as np
import cv2
ap = argparse.ArgumentParser(); ap.add_argument("--ids", default="0-19"); ap.add_argument("--side", type=float, default=0.5); a = ap.parse_args()
lo, hi = (int(x) for x in a.ids.split("-"))
ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "models")
for i in range(lo, hi + 1):
    name = f"apriltag36h11_{i}"; d = os.path.join(ROOT, name, "materials", "textures"); os.makedirs(d, exist_ok=True)
    src = f"https://raw.githubusercontent.com/AprilRobotics/apriltag-imgs/master/tag36h11/tag36_11_{i:05d}.png"
    raw = np.frombuffer(urllib.request.urlopen(src).read(), np.uint8)
    img = cv2.imdecode(raw, cv2.IMREAD_UNCHANGED)
    rgb = img[:, :, :3] if img.ndim == 3 else cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
    big = cv2.resize(rgb, (400, 400), interpolation=cv2.INTER_NEAREST)
    cv2.imwrite(os.path.join(d, "tag.png"), big)
    s = a.side
    open(os.path.join(ROOT, name, "model.config"), "w").write(f"""<?xml version="1.0"?>
<model><name>{name}</name><version>1.0</version><sdf version="1.9">model.sdf</sdf>
<description>AprilTag tag36h11 id {i}, {s} m overall ({0.8 * s:.3f} m black square), visual only.</description></model>
""")
    open(os.path.join(ROOT, name, "model.sdf"), "w").write(f"""<?xml version="1.0" ?>
<sdf version="1.9">
  <!-- AprilTag tag36h11 id {i}: generated by sim/tools/make_apriltag_models.py. Visual only (no collision). -->
  <model name="{name}">
    <static>true</static>
    <link name="link">
      <visual name="visual">
        <cast_shadows>false</cast_shadows>
        <geometry><box><size>{s} {s} 0.002</size></box></geometry>
        <material>
          <ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse><specular>0 0 0 1</specular>
          <pbr><metal><albedo_map>model://{name}/materials/textures/tag.png</albedo_map><roughness>1</roughness><metalness>0</metalness></metal></pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
""")
    print("wrote", name)
